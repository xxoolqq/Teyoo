/**
 * 「易混条目语义边界」段：只列目录里真实存在的编码。
 *
 * 这段是纯提示词，不进本地校验 —— 它的作用是压低两类误标：把「求分布列」
 * 当成任意概率题、把「求不等式解集」当成考查二次函数零点与方程解的对应关系。
 * 目录换了（比如换成全量 773 条）而这里没跟上时，buildKnowledgeBoundaryBlock
 * 会自动跳过已不存在的编码，不会让 prompt 指向一个选不中的码。
 */
const KNOWLEDGE_BOUNDARIES: readonly (readonly [code: string, note: string])[] = [
  [
    '1932',
    '本点的任务是利用二项分布列出随机变量全部可能取值及相应概率。只求一个事件、一个取值或某个范围的概率，不等于求分布列；不能仅因用到二项概率公式或别名“二项分布”就把本点当作通用概率标签。仍需与完整目录中更贴合所求事件的条目比较。'
  ],
  [
    '1097',
    '本点针对二次函数零点与对应一元二次方程解之间的联系。仅把给定数值代入方程验证或求解方程，不等于考查函数零点与方程解的对应关系。求二次不等式解集时仅把方程根作为中间计算结果，不足以证明题目直接考查这种对应关系；应区分求方程根、判断函数零点以及解不等式的实际目标。'
  ]
]

export function buildKnowledgeBoundaryBlock(
  catalog: readonly CatalogRow[] = KNOWLEDGE_CATALOG
): string {
  const codes = new Set(catalog.map(([code]) => code))
  const kept = KNOWLEDGE_BOUNDARIES.filter(([code]) => codes.has(code))
  return kept.length === 0 ? '' : JSON.stringify(kept)
}
